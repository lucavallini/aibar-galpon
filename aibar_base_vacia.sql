-- 13. VALIDAR DETALLE AGROQUÍMICO
-- =========================================================

CREATE OR REPLACE FUNCTION public.validar_detalle_agroquimico()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_categoria VARCHAR(20);
BEGIN

    SELECT p.categoria
    INTO v_categoria
    FROM public.palet pa
    INNER JOIN public.producto p
        ON p.id = pa.producto_id
    WHERE pa.id = NEW.palet_id;


    IF v_categoria IS NULL THEN
        RAISE EXCEPTION
            'El palet no existe';
    END IF;


    IF v_categoria <> 'agroquimico' THEN
        RAISE EXCEPTION
            'El palet no corresponde a un producto agroquímico';
    END IF;


    RETURN NEW;

END;
$$;



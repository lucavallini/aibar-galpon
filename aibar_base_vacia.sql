-- =========================================================
-- 16. REGISTRAR MOVIMIENTO
-- =========================================================
--
-- ESTA FUNCIÓN MODIFICA:
--
--   cantidad_disponible
--   estado
--
-- Además crea el registro histórico.
--
-- Todo ocurre dentro de una única transacción.
--
-- TODOS LOS TIPOS RESTAN STOCK:
--
--   venta  -> resta stock
--   salida -> resta stock
--   ajuste -> resta stock
--
-- Para corregir un error de tipeo (sumar stock), no se usa
-- esta función: se usa corregir_movimiento() (sección 16.5).
--
-- =========================================================

CREATE OR REPLACE FUNCTION public.registrar_movimiento(
    p_palet_id BIGINT,
    p_tipo VARCHAR,
    p_cantidad NUMERIC
)
RETURNS public.movimiento
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$

DECLARE
    v_usuario_id UUID;
    v_palet public.palet%ROWTYPE;
    v_nueva_cantidad NUMERIC;
    v_nuevo_estado VARCHAR(20);
    v_movimiento public.movimiento%ROWTYPE;

BEGIN

    -- =====================================================
    -- 1. Usuario autenticado
    -- =====================================================

    v_usuario_id := auth.uid();

    IF v_usuario_id IS NULL THEN
        RAISE EXCEPTION
            'Usuario no autenticado';
    END IF;


    -- =====================================================
    -- 2. Verificar operario
    -- =====================================================

    IF NOT public.es_operario() THEN
        RAISE EXCEPTION
            'Solo los operarios pueden registrar movimientos';
    END IF;


    -- =====================================================
    -- 3. Validar tipo
    -- =====================================================

    IF p_tipo NOT IN (
        'venta',
        'salida',
        'ajuste'
    ) THEN

        RAISE EXCEPTION
            'Tipo de movimiento inválido';

    END IF;


    -- =====================================================
    -- 4. Validar cantidad
    -- =====================================================

    IF p_cantidad IS NULL
       OR p_cantidad <= 0 THEN

        RAISE EXCEPTION
            'La cantidad debe ser mayor que cero';

    END IF;


    -- =====================================================
    -- 5. Obtener palet y bloquearlo
    -- =====================================================
    --
    -- FOR UPDATE evita problemas si dos operarios
    -- intentan modificar el mismo palet al mismo tiempo.
    --
    -- =====================================================

    SELECT *
    INTO v_palet
    FROM public.palet
    WHERE id = p_palet_id
    FOR UPDATE;


    IF NOT FOUND THEN
        RAISE EXCEPTION
            'El palet no existe';
    END IF;


    -- =====================================================
    -- 6. Verificar estado
    -- =====================================================

    IF v_palet.estado = 'baja' THEN
        RAISE EXCEPTION
            'El palet se encuentra dado de baja';
    END IF;


    IF v_palet.cantidad_disponible = 0 THEN
        RAISE EXCEPTION
            'El palet no tiene stock disponible';
    END IF;


    -- =====================================================
    -- 7. Verificar stock suficiente
    -- =====================================================

    IF p_cantidad > v_palet.cantidad_disponible THEN

        RAISE EXCEPTION
            'Stock insuficiente. Disponible: %, solicitado: %',
            v_palet.cantidad_disponible,
            p_cantidad;

    END IF;


    -- =====================================================
    -- 8. CALCULAR NUEVO STOCK (siempre se resta)
    -- =====================================================

    v_nueva_cantidad :=
        v_palet.cantidad_disponible - p_cantidad;


    -- =====================================================
    -- 9. DETERMINAR NUEVO ESTADO
    -- =====================================================

    IF v_nueva_cantidad = 0 THEN

        v_nuevo_estado := 'vacio';

    ELSIF v_nueva_cantidad <
          v_palet.cantidad_inicial THEN

        v_nuevo_estado := 'parcial';

    ELSE

        v_nuevo_estado := 'activo';

    END IF;


    -- =====================================================
    -- 10. ACTUALIZAR PALET
    -- =====================================================

    UPDATE public.palet
    SET
        cantidad_disponible = v_nueva_cantidad,
        estado = v_nuevo_estado
    WHERE id = p_palet_id;


    -- =====================================================
    -- 11. CREAR HISTORIAL
    -- =====================================================

    INSERT INTO public.movimiento (
        palet_id,
        usuario_id,
        tipo,
        cantidad
    )
    VALUES (
        p_palet_id,
        v_usuario_id,
        p_tipo,
        p_cantidad
    )
    RETURNING *
    INTO v_movimiento;


    -- =====================================================
    -- 12. DEVOLVER MOVIMIENTO
    -- =====================================================

    RETURN v_movimiento;

END;
$$;


-- =========================================================
-- 16.5. CORREGIR MOVIMIENTO (deshacer un error de tipeo)
-- =========================================================
--
-- Única función que puede sumar stock. No reemplaza ni
-- edita el movimiento original: crea un movimiento nuevo,
-- de tipo 'correccion', que lo compensa. El historial
-- completo queda intacto y auditable.
--
-- Restricciones:
--   - Solo puede corregir el ÚLTIMO movimiento del palet
--     (no cualquiera del historial).
--   - Solo dentro de los 30 minutos posteriores a su carga.
--   - No se puede corregir una corrección.
--   - El motivo es obligatorio (queda guardado en movimiento.motivo).
--
-- El botón "corregir" del front debe llamar únicamente a
-- esta función, nunca insertar un 'ajuste' con signo
-- invertido ni tocar el palet directamente.
--
-- =========================================================

CREATE OR REPLACE FUNCTION public.corregir_movimiento(
    p_movimiento_id BIGINT,
    p_motivo VARCHAR
)
RETURNS public.movimiento
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$

DECLARE
    v_usuario_id UUID;
    v_original public.movimiento%ROWTYPE;
    v_ultimo_id BIGINT;
    v_palet public.palet%ROWTYPE;
    v_nueva_cantidad NUMERIC;
    v_nuevo_estado VARCHAR(20);
    v_movimiento public.movimiento%ROWTYPE;

BEGIN

    -- =====================================================
    -- 1. Usuario autenticado y operario
    -- =====================================================

    v_usuario_id := auth.uid();

    IF v_usuario_id IS NULL THEN
        RAISE EXCEPTION
            'Usuario no autenticado';
    END IF;

    IF NOT public.es_operario() THEN
        RAISE EXCEPTION
            'Solo los operarios pueden corregir movimientos';
    END IF;


    -- =====================================================
    -- 2. Validar motivo
    -- =====================================================

    IF p_motivo IS NULL OR btrim(p_motivo) = '' THEN
        RAISE EXCEPTION
            'Es obligatorio indicar el motivo de la corrección';
    END IF;


    -- =====================================================
    -- 3. Obtener el movimiento original
    -- =====================================================

    SELECT *
    INTO v_original
    FROM public.movimiento
    WHERE id = p_movimiento_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION
            'El movimiento no existe';
    END IF;

    IF v_original.tipo = 'correccion' THEN
        RAISE EXCEPTION
            'No se puede corregir una corrección';
    END IF;


    -- =====================================================
    -- 4. Debe ser el ÚLTIMO movimiento de ese palet
    -- =====================================================

    SELECT id
    INTO v_ultimo_id
    FROM public.movimiento
    WHERE palet_id = v_original.palet_id
    ORDER BY fecha_hora DESC
    LIMIT 1;

    IF v_ultimo_id IS DISTINCT FROM p_movimiento_id THEN
        RAISE EXCEPTION
            'Solo se puede corregir el último movimiento registrado en el palet';
    END IF;


    -- =====================================================
    -- 5. Ventana de tiempo: 30 minutos
    -- =====================================================

    IF NOW() - v_original.fecha_hora > INTERVAL '30 minutes' THEN
        RAISE EXCEPTION
            'El movimiento ya no puede corregirse (fuera de plazo)';
    END IF;


    -- =====================================================
    -- 6. Bloquear el palet y recalcular stock
    -- =====================================================

    SELECT *
    INTO v_palet
    FROM public.palet
    WHERE id = v_original.palet_id
    FOR UPDATE;

    v_nueva_cantidad :=
        v_palet.cantidad_disponible + v_original.cantidad;

    IF v_nueva_cantidad > v_palet.cantidad_inicial THEN
        RAISE EXCEPTION
            'La corrección dejaría el stock por encima de la cantidad inicial del palet';
    END IF;

    IF v_nueva_cantidad = v_palet.cantidad_inicial THEN
        v_nuevo_estado := 'activo';
    ELSIF v_nueva_cantidad = 0 THEN
        v_nuevo_estado := 'vacio';
    ELSE
        v_nuevo_estado := 'parcial';
    END IF;


    -- =====================================================
    -- 7. Actualizar palet
    -- =====================================================

    UPDATE public.palet
    SET
        cantidad_disponible = v_nueva_cantidad,
        estado = v_nuevo_estado
    WHERE id = v_original.palet_id;


    -- =====================================================
    -- 8. Crear el movimiento de corrección
    -- =====================================================

    INSERT INTO public.movimiento (
        palet_id,
        usuario_id,
        tipo,
        cantidad,
        corrige_a,
        motivo
    )
    VALUES (
        v_original.palet_id,
        v_usuario_id,
        'correccion',
        v_original.cantidad,
        p_movimiento_id,
        p_motivo
    )
    RETURNING *
    INTO v_movimiento;


    RETURN v_movimiento;

END;
$$;



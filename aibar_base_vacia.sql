CREATE OR REPLACE FUNCTION public.crear_palet_completo(
    p_producto_id BIGINT,
    p_lote VARCHAR,
    p_cantidad_inicial NUMERIC,
    p_galpon SMALLINT,
    p_sector VARCHAR DEFAULT NULL,
    p_fecha_ingreso DATE DEFAULT NULL,

    -- Solo se usan si el producto es agroquímico
    p_fecha_elaboracion DATE DEFAULT NULL,
    p_fecha_vencimiento DATE DEFAULT NULL,

    -- Solo se usan si el producto es semilla
    p_hibrido VARCHAR DEFAULT NULL,
    p_calibre VARCHAR DEFAULT NULL,

    -- NULL = mercadería propia de AIBAR
    p_cliente_id BIGINT DEFAULT NULL,

    -- Primera nota de la bitácora. Opcional.
    p_observacion VARCHAR DEFAULT NULL
)
RETURNS public.palet
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public
AS $$

DECLARE
    v_categoria VARCHAR(20);
    v_palet public.palet%ROWTYPE;
    v_observacion VARCHAR(500);

BEGIN

    IF NOT public.es_operario() THEN
        RAISE EXCEPTION
            'Solo los operarios pueden dar de alta palets';
    END IF;


    SELECT categoria
    INTO v_categoria
    FROM public.producto
    WHERE id = p_producto_id;

    IF v_categoria IS NULL THEN
        RAISE EXCEPTION
            'El producto indicado no existe';
    END IF;


    IF p_cliente_id IS NOT NULL
       AND NOT EXISTS (
           SELECT 1 FROM public.cliente WHERE id = p_cliente_id
       ) THEN
        RAISE EXCEPTION
            'El cliente indicado no existe';
    END IF;


    INSERT INTO public.palet (
        producto_id,
        lote,
        cantidad_inicial,
        galpon,
        sector,
        fecha_ingreso,
        cliente_id
    )
    VALUES (
        p_producto_id,
        p_lote,
        p_cantidad_inicial,
        p_galpon,
        NULLIF(btrim(p_sector), ''),
        COALESCE(p_fecha_ingreso, CURRENT_DATE),
        p_cliente_id
    )
    RETURNING *
    INTO v_palet;


    IF v_categoria = 'agroquimico' THEN

        INSERT INTO public.detalle_agroquimico (
            palet_id,
            fecha_elaboracion,
            fecha_vencimiento
        )
        VALUES (
            v_palet.id,
            p_fecha_elaboracion,
            p_fecha_vencimiento
        );

    ELSIF v_categoria = 'semilla' THEN

        INSERT INTO public.detalle_semilla (
            palet_id,
            hibrido,
            calibre
        )
        VALUES (
            v_palet.id,
            NULLIF(btrim(p_hibrido), ''),
            NULLIF(btrim(p_calibre), '')
        );

    ELSE

        RAISE EXCEPTION
            'Categoría de producto desconocida: %',
            v_categoria;

    END IF;


    -- La observación inicial entra en la misma transacción
    -- que el palet: o queda todo, o no queda nada.
    v_observacion := NULLIF(btrim(p_observacion), '');

    IF v_observacion IS NOT NULL THEN

        INSERT INTO public.observacion_palet (
            palet_id,
            usuario_id,
            texto
        )
        VALUES (
            v_palet.id,
            auth.uid(),
            v_observacion
        );

    END IF;


    SELECT *
    INTO v_palet
    FROM public.palet
    WHERE id = v_palet.id;

    RETURN v_palet;

END;
$$;


REVOKE ALL

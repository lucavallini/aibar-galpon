-- =========================================================
-- AIBAR — SISTEMA DE TRAZABILIDAD DE PALETS
-- BASE COMPLETA PARA UN PROYECTO NUEVO
-- =========================================================
--
-- QUÉ ES ESTE ARCHIVO
--
-- Todo el esquema en un solo script: tablas, índices,
-- funciones, triggers, vistas, permisos y policies de RLS.
-- No trae un solo dato: ni usuarios, ni productos, ni
-- clientes, ni palets. La base queda vacía y lista.
--
-- Es el schema original más las ocho migraciones que se
-- fueron aplicando, en el mismo orden en que se aplicaron.
-- Corriéndolo entero se llega exactamente al estado actual.
--
--
-- CÓMO SE CORRE
--
-- En el SQL Editor de Supabase, sobre un proyecto NUEVO y
-- vacío. Se pega completo y se ejecuta de una sola vez.
--
-- ⚠️ Sobre un proyecto que ya tenga datos, no. Hay DROPs de
-- vistas y de funciones acá adentro.
--
-- Los NOTICE del tipo «policy … does not exist, skipping» son
-- normales: el script está escrito para poder recorrerse dos
-- veces sin romperse.
--
-- Probado de punta a punta contra un Postgres 17 limpio: las
-- 8 tablas quedan con RLS, las 2 vistas con security_invoker,
-- y el circuito real (alta de palet, descuento de stock, baja,
-- observaciones) funciona con los permisos puestos.
--
--
-- DESPUÉS DE CORRERLO
--
-- La base queda sin un solo usuario, y como el registro
-- público está cerrado a propósito, no hay forma de crear el
-- primero desde la app. Hay que crearlo a mano:
--
--   1. Authentication → Users → Add user, con un email real
--      y su contraseña. El trigger le crea la fila en
--      `public.usuario` con rol 'operario'.
--   2. Volver acá y correr:
--
--        UPDATE public.usuario
--           SET rol = 'jefe', nombre = 'Nombre Apellido'
--         WHERE id = '<el uuid que quedó en Authentication>';
--
-- Ese primer jefe entra con su email. De ahí en más, las
-- altas las hace él desde el panel administrativo y son por
-- DNI.
--
-- =========================================================





-- =========================================================
-- 12. PROTEGER DATOS DE STOCK
-- =========================================================
--
-- Impide modificar directamente:
--
--   cantidad_inicial
--   cantidad_disponible
--   estado
--
-- registrar_movimiento() y corregir_movimiento() son los
-- únicos mecanismos autorizados para modificar
-- cantidad_disponible y estado (ambos corren como
-- SECURITY DEFINER, por eso current_user != session_user
-- cuando pasan por acá y no disparan la excepción).
--
-- =========================================================

CREATE OR REPLACE FUNCTION public.proteger_stock_palet()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN

    IF NEW.cantidad_inicial IS DISTINCT FROM OLD.cantidad_inicial THEN
        RAISE EXCEPTION
            'La cantidad inicial no puede modificarse después de crear el palet';
    END IF;

    IF (
        NEW.cantidad_disponible IS DISTINCT FROM OLD.cantidad_disponible
        OR NEW.estado IS DISTINCT FROM OLD.estado
    )
    AND current_user = session_user THEN

        RAISE EXCEPTION
            'El stock solo puede modificarse mediante registrar_movimiento() o corregir_movimiento()';

    END IF;

    RETURN NEW;

END;
$$;


CREATE TRIGGER trigger_proteger_stock_palet
BEFORE UPDATE ON public.palet
FOR EACH ROW
EXECUTE FUNCTION public.proteger_stock_palet();


-- =========================================================
-- 12.5. PROTEGER IDENTIDAD DEL PALET
-- =========================================================
--
-- Un palet que ya tiene movimientos no puede cambiar:
--   - producto
--   - lote
--
-- =========================================================

CREATE OR REPLACE FUNCTION public.proteger_identidad_palet()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    v_categoria_nueva VARCHAR(20);
    v_tiene_movimientos BOOLEAN;
    v_tiene_detalle_agro BOOLEAN;
    v_tiene_detalle_semilla BOOLEAN;
BEGIN

    IF NEW.producto_id IS DISTINCT FROM OLD.producto_id
       OR NEW.lote IS DISTINCT FROM OLD.lote THEN

        SELECT EXISTS (
            SELECT 1
            FROM public.movimiento
            WHERE palet_id = OLD.id
        )
        INTO v_tiene_movimientos;

        IF v_tiene_movimientos THEN
            RAISE EXCEPTION
                'No se puede cambiar producto o lote de un palet que ya tiene movimientos';
        END IF;

    END IF;


    IF NEW.producto_id IS DISTINCT FROM OLD.producto_id THEN

        SELECT categoria
        INTO v_categoria_nueva
        FROM public.producto
        WHERE id = NEW.producto_id;

        IF v_categoria_nueva IS NULL THEN
            RAISE EXCEPTION
                'El producto indicado no existe';
        END IF;


        SELECT EXISTS (
            SELECT 1
            FROM public.detalle_agroquimico
            WHERE palet_id = OLD.id
        )
        INTO v_tiene_detalle_agro;


        SELECT EXISTS (
            SELECT 1
            FROM public.detalle_semilla
            WHERE palet_id = OLD.id
        )
        INTO v_tiene_detalle_semilla;


        IF v_categoria_nueva <> 'agroquimico'
           AND v_tiene_detalle_agro THEN

            RAISE EXCEPTION
                'No se puede cambiar el producto: el palet tiene un detalle agroquímico';

        END IF;


        IF v_categoria_nueva <> 'semilla'
           AND v_tiene_detalle_semilla THEN

            RAISE EXCEPTION
                'No se puede cambiar el producto: el palet tiene un detalle de semilla';

        END IF;

    END IF;


    RETURN NEW;

END;
$$;


CREATE TRIGGER trigger_proteger_identidad_palet
BEFORE UPDATE ON public.palet
FOR EACH ROW
EXECUTE FUNCTION public.proteger_identidad_palet();



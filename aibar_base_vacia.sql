-- =========================================================
-- ROLES Y REGLAS DEL SISTEMA
-- =========================================================
--
-- OPERARIO:
--   - Crear/modificar/eliminar productos
--   - Crear/modificar/eliminar palets (excepto stock)
--   - Crear/modificar/eliminar detalles
--   - Registrar movimientos
--   - Corregir el último movimiento (ventana de 30 min)
--   - Consultar información
--
-- JEFE:
--   - Consultar toda la información
--   - Buscar y filtrar
--   - Ver movimientos
--   - No modificar información
--
-- STOCK:
--   cantidad_inicial      -> solo al crear palet
--   cantidad_disponible   -> registrar_movimiento() / corregir_movimiento()
--   estado                -> registrar_movimiento() / corregir_movimiento()
--
-- MOVIMIENTOS:
--   - Se crean únicamente mediante registrar_movimiento()
--     o corregir_movimiento()
--   - No se pueden modificar
--   - No se pueden eliminar
--
-- TIPOS DE MOVIMIENTO:
--   - venta        -> resta stock
--   - salida       -> resta stock
--   - ajuste       -> resta stock
--   - correccion   -> suma stock (solo vía corregir_movimiento)
--
-- IMPORTANTE:
--   venta / salida / ajuste SIEMPRE restan stock.
--   Solo 'correccion' puede sumar, y solo la puede generar
--   la función corregir_movimiento(), nunca un INSERT directo
--   ni registrar_movimiento().
--
-- Para ingresar stock nuevo (mercadería que llega) se debe
-- crear un nuevo palet.
--
-- =========================================================


-- =========================================================
-- 1. USUARIOS
-- =========================================================

CREATE TABLE public.usuario (
    id UUID PRIMARY KEY
        REFERENCES auth.users(id)
        ON DELETE CASCADE,

    nombre VARCHAR(100) NOT NULL,

    rol VARCHAR(20) NOT NULL
        CHECK (
            rol IN ('operario', 'jefe')
        ),

    activo BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


-- =========================================================
-- 2. PRODUCTOS
-- =========================================================

CREATE TABLE public.producto (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    nombre VARCHAR(150) NOT NULL,

    categoria VARCHAR(20) NOT NULL
        CHECK (
            categoria IN (
                'agroquimico',
                'semilla'
            )
        ),

    unidad_medida VARCHAR(20) NOT NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


-- =========================================================
-- 3. PALETS
-- =========================================================

CREATE TABLE public.palet (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    producto_id BIGINT NOT NULL
        REFERENCES public.producto(id)
        ON DELETE RESTRICT,

    lote VARCHAR(50) NOT NULL,

    cantidad_inicial NUMERIC(10,2) NOT NULL
        CHECK (
            cantidad_inicial > 0
        ),

    cantidad_disponible NUMERIC(10,2) NOT NULL
        CHECK (
            cantidad_disponible >= 0
            AND cantidad_disponible <= cantidad_inicial
        ),

    galpon SMALLINT NOT NULL
        CHECK (
            galpon IN (1, 2, 3)
        ),

    sector VARCHAR(50),

    fecha_ingreso DATE NOT NULL
        DEFAULT CURRENT_DATE,

    estado VARCHAR(20) NOT NULL
        DEFAULT 'activo'
        CHECK (
            estado IN (
                'activo',
                'parcial',
                'vacio',
                'baja'
            )
        ),

    created_at TIMESTAMPTZ NOT NULL
        DEFAULT NOW(),

    updated_at TIMESTAMPTZ NOT NULL
        DEFAULT NOW()
);


-- =========================================================
-- 4. DETALLE AGROQUÍMICO
-- =========================================================

CREATE TABLE public.detalle_agroquimico (
    palet_id BIGINT PRIMARY KEY
        REFERENCES public.palet(id)
        ON DELETE CASCADE,

    fecha_elaboracion DATE,

    fecha_vencimiento DATE,

    CHECK (
        fecha_vencimiento IS NULL
        OR fecha_elaboracion IS NULL
        OR fecha_vencimiento >= fecha_elaboracion
    )
);


-- =========================================================
-- 5. DETALLE SEMILLA
-- =========================================================

CREATE TABLE public.detalle_semilla (
    palet_id BIGINT PRIMARY KEY
        REFERENCES public.palet(id)
        ON DELETE CASCADE,

    hibrido VARCHAR(100),

    calibre VARCHAR(50)
);


-- =========================================================
-- 6. MOVIMIENTOS
-- =========================================================
--
-- HISTORIAL INMUTABLE
--
-- Nunca se actualiza.
-- Nunca se elimina.
--
-- corrige_a: si el movimiento es una 'correccion', apunta
-- al movimiento original que está corrigiendo. NULL en
-- cualquier otro caso.
--
-- motivo: obligatorio solo para 'correccion', para dejar
-- registrado por qué se corrigió.
--
-- =========================================================

CREATE TABLE public.movimiento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    palet_id BIGINT NOT NULL
        REFERENCES public.palet(id)
        ON DELETE RESTRICT,

    usuario_id UUID NOT NULL
        REFERENCES public.usuario(id)
        ON DELETE RESTRICT,

    tipo VARCHAR(20) NOT NULL
        CHECK (
            tipo IN (
                'venta',
                'salida',
                'ajuste',
                'correccion'
            )
        ),

    cantidad NUMERIC(10,2) NOT NULL
        CHECK (
            cantidad > 0
        ),

    corrige_a BIGINT
        REFERENCES public.movimiento(id),

    motivo VARCHAR(255),

    fecha_hora TIMESTAMPTZ NOT NULL
        DEFAULT NOW(),

    CHECK (
        tipo <> 'correccion' OR motivo IS NOT NULL
    ),

    CHECK (
        tipo = 'correccion' OR corrige_a IS NULL
    )
);



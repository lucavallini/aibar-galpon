CREATE POLICY "usuario_update_jefe"
ON public.usuario
FOR UPDATE
TO authenticated
USING (
    public.es_jefe()
    AND id <> auth.uid()
)
WITH CHECK (
    public.es_jefe()
    AND id <> auth.uid()
);



-- =========================================================
-- 10. CREAR USUARIO AUTOMÁTICAMENTE
-- =========================================================
--
-- Todo usuario registrado empieza como OPERARIO.
--
-- Para convertirlo en jefe:
--
-- UPDATE public.usuario
-- SET rol = 'jefe'
-- WHERE id = 'UUID';
--
-- =========================================================

CREATE OR REPLACE FUNCTION public.crear_usuario()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN

    INSERT INTO public.usuario (
        id,
        nombre,
        rol,
        activo
    )
    VALUES (
        NEW.id,

        COALESCE(
            NEW.raw_user_meta_data ->> 'nombre',
            NEW.email
        ),

        'operario',

        TRUE
    );

    RETURN NEW;

END;
$$;


CREATE TRIGGER trigger_crear_usuario
AFTER INSERT ON auth.users
FOR EACH ROW
EXECUTE FUNCTION public.crear_usuario();



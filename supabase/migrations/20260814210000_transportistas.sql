-- =========================================================
-- 7. LA SALIDA REGISTRA QUIÉN SE LA LLEVÓ
-- =========================================================
--
-- Es la misma función de siempre con un parámetro más. Toda
-- la lógica de stock —el bloqueo FOR UPDATE, el chequeo de
-- disponible, el cálculo del estado— queda **exactamente
-- igual**: acá solo se suma a quién se le entregó.
--
-- El chofer se guarda solo en venta y salida. En un ajuste no
-- hay camión: es una rotura, un derrame o un recuento que no
-- cuadra, y anotar un transportista ahí sería inventar que
-- alguien se llevó algo.
--
-- Sigue siendo SECURITY DEFINER porque necesita saltear el
-- trigger `proteger_stock_palet()`, que es lo que impide
-- tocar el stock desde el cliente.
--
-- =========================================================

DROP FUNCTION IF EXISTS public.registrar_movimiento(BIGINT, VARCHAR, NUMERIC);

CREATE OR REPLACE FUNCTION public.registrar_movimiento(
    p_palet_id         BIGINT,
    p_tipo             VARCHAR,
    p_cantidad         NUMERIC,
    p_transportista_id BIGINT DEFAULT NULL
)
RETURNS public.movimiento
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$

DECLARE
    v_usuario_id UUID;
    v_palet public.palet%ROWTYPE;
    v_nueva_cantidad NUMERIC;
    v_nuevo_estado VARCHAR(20);
    v_movimiento public.movimiento%ROWTYPE;
    v_transportista_id BIGINT;

BEGIN

    v_usuario_id := auth.uid();

    IF v_usuario_id IS NULL THEN
        RAISE EXCEPTION 'Usuario no autenticado';
    END IF;

    IF NOT public.es_operario() THEN
        RAISE EXCEPTION 'Solo los operarios pueden registrar movimientos';
    END IF;

    IF p_tipo NOT IN ('venta', 'salida', 'ajuste') THEN
        RAISE EXCEPTION 'Tipo de movimiento inválido';
    END IF;

    IF p_cantidad IS NULL OR p_cantidad <= 0 THEN
        RAISE EXCEPTION 'La cantidad debe ser mayor que cero';
    END IF;

    -- ----- Quién se la lleva -----
    --
    -- En un ajuste se descarta aunque venga: no hubo ningún
    -- camión, y dejarlo pasar mancharía el historial con
    -- entregas que no existieron.
    v_transportista_id := CASE
        WHEN p_tipo IN ('venta', 'salida') THEN p_transportista_id
        ELSE NULL
    END;

    IF v_transportista_id IS NOT NULL
       AND NOT EXISTS (
           SELECT 1 FROM public.transportista WHERE id = v_transportista_id
       ) THEN
        RAISE EXCEPTION 'El transportista indicado no existe';
    END IF;

    -- FOR UPDATE: si dos operarios descuentan del mismo palet a la vez, el
    -- segundo espera y ve el stock ya actualizado.
    SELECT *
    INTO v_palet
    FROM public.palet
    WHERE id = p_palet_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'El palet no existe';
    END IF;

    IF v_palet.estado = 'baja' THEN
        RAISE EXCEPTION 'El palet se encuentra dado de baja';
    END IF;

    IF v_palet.cantidad_disponible = 0 THEN
        RAISE EXCEPTION 'El palet no tiene stock disponible';
    END IF;

    IF p_cantidad > v_palet.cantidad_disponible THEN
        RAISE EXCEPTION
            'Stock insuficiente. Disponible: %, solicitado: %',
            v_palet.cantidad_disponible,
            p_cantidad;
    END IF;

    v_nueva_cantidad := v_palet.cantidad_disponible - p_cantidad;

    IF v_nueva_cantidad = 0 THEN
        v_nuevo_estado := 'vacio';
    ELSIF v_nueva_cantidad < v_palet.cantidad_inicial THEN
        v_nuevo_estado := 'parcial';
    ELSE
        v_nuevo_estado := 'activo';
    END IF;

    UPDATE public.palet
    SET cantidad_disponible = v_nueva_cantidad,
        estado = v_nuevo_estado
    WHERE id = p_palet_id;

    INSERT INTO public.movimiento (
        palet_id,
        usuario_id,
        tipo,
        cantidad,
        transportista_id
    )
    VALUES (
        p_palet_id,
        v_usuario_id,
        p_tipo,
        p_cantidad,
        v_transportista_id
    )
    RETURNING *
    INTO v_movimiento;

    RETURN v_movimiento;

END;
$$;

REVOKE ALL ON FUNCTION public.registrar_movimiento(BIGINT, VARCHAR, NUMERIC, BIGINT)
    FROM PUBLIC, anon;

GRANT EXECUTE ON FUNCTION public.registrar_movimiento(BIGINT, VARCHAR, NUMERIC, BIGINT)
    TO authenticated;


-- =========================================================
-- 8. EL PANEL VE QUIÉN TRAJO CADA PALET
-- =========================================================
--
-- ⚠️ `security_invoker = on`: sin eso la vista correría con
-- los permisos de quien la creó y saltearía RLS por completo.
--
-- =========================================================

DROP VIEW IF EXISTS public.vista_palet_gerencia;

CREATE VIEW public.vista_palet_gerencia
WITH (security_invoker = on)
AS
SELECT
    p.id,
    p.producto_id,
    p.lote,
    p.cantidad_inicial,
    p.cantidad_disponible,
    p.unidad_medida,
    p.galpon,
    p.sector,
    p.fecha_ingreso,
    p.estado,

    pr.nombre           AS producto_nombre,
    pr.categoria        AS producto_categoria,
    pr.marca            AS producto_marca,
    pr.principio_activo AS producto_principio_activo,
    pr.concentracion    AS producto_concentracion,

    p.cliente_id,
    c.nombre            AS cliente_nombre,

    p.transportista_id,
    t.nombre            AS transportista_nombre,

    da.fecha_elaboracion,
    da.fecha_vencimiento,
    ds.hibrido,
    ds.calibre,

    (da.fecha_vencimiento - CURRENT_DATE) AS dias_para_vencer,

    ultimo.fecha_hora AS ultimo_movimiento,

    (CURRENT_DATE - COALESCE(ultimo.fecha_hora::date, p.fecha_ingreso))
        AS dias_sin_movimiento,

    COALESCE(obs.cantidad, 0) AS cantidad_observaciones,

    ultima_obs.texto      AS ultima_observacion,
    ultima_obs.created_at AS ultima_observacion_fecha,
    ultima_obs.autor      AS ultima_observacion_autor

FROM public.palet p

INNER JOIN public.producto pr
    ON pr.id = p.producto_id

LEFT JOIN public.cliente c
    ON c.id = p.cliente_id

LEFT JOIN public.transportista t
    ON t.id = p.transportista_id

LEFT JOIN public.detalle_agroquimico da
    ON da.palet_id = p.id

LEFT JOIN public.detalle_semilla ds
    ON ds.palet_id = p.id

LEFT JOIN LATERAL (
    SELECT max(m.fecha_hora) AS fecha_hora
    FROM public.movimiento m
    WHERE m.palet_id = p.id
) ultimo ON TRUE

LEFT JOIN LATERAL (
    SELECT count(*) AS cantidad
    FROM public.observacion_palet o
    WHERE o.palet_id = p.id
) obs ON TRUE

LEFT JOIN LATERAL (
    SELECT o.texto, o.created_at, u.nombre AS autor
    FROM public.observacion_palet o
    LEFT JOIN public.usuario u ON u.id = o.usuario_id
    WHERE o.palet_id = p.id
    ORDER BY o.created_at DESC, o.id DESC
    LIMIT 1
) ultima_obs ON TRUE;

GRANT SELECT ON public.vista_palet_gerencia TO authenticated;
REVOKE ALL ON public.vista_palet_gerencia FROM anon;


COMMIT;



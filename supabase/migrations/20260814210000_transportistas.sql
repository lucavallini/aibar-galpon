-- =========================================================
-- AIBAR
-- TRANSPORTISTAS: QUIÉN TRAJO Y QUIÉN SE LLEVÓ
-- =========================================================
--
-- QUÉ AGREGA
--
-- Hasta ahora el depósito registraba qué entró y qué salió,
-- pero no en manos de quién. Cuando aparece un faltante o
-- una carga mal entregada, «salieron 400 kg el martes» no
-- alcanza: hace falta saber qué camión se los llevó.
--
-- Se suman dos vínculos, y son distintos a propósito:
--
--   palet.transportista_id      QUIÉN LO TRAJO
--     Es un dato del ingreso y no cambia nunca más.
--
--   movimiento.transportista_id QUIÉN SE LO LLEVÓ
--     Va en el movimiento y no en el palet porque un palet
--     sale de a partes: 400 kg con un chofer el martes y 300
--     con otro el jueves. En el palet solo se podría guardar
--     el último, y se perderían los anteriores.
--
-- Los dos son opcionales: si el operario no llegó a
-- preguntar quién era, el alta y la salida no se traban.
--
--
-- LOS DATOS
--
-- Los 43 choferes y las 9 empresas vienen de la base de
-- viajes que ya usa AIBAR. Se importan normalizados:
--
--   - Los nombres venían mezclados ('diego mateo' junto a
--     'DAMIAN ARCURE ') y quedan capitalizados y sin espacios
--     de sobra: 'Diego Mateo', 'Damian Arcure'.
--   - Una empresa traía un espacio duro invisible
--     ('ALLPA<NBSP>SRL') que se normaliza a un espacio común;
--     si no, buscarla escribiendo el nombre no la encontraría.
--   - No se importa el DNI: no hace falta para identificar al
--     chofer en el depósito, y en el origen venía irregular
--     (números de 7 y de 9 dígitos).
--
-- Se puede correr más de una vez sin duplicar: los INSERT
-- van con ON CONFLICT DO NOTHING sobre el nombre.
--
--
-- CÓMO SE CORRE
--
-- En el SQL Editor, entero y de una vez.
--
-- =========================================================

BEGIN;


-- =========================================================
-- 1. LAS EMPRESAS DE TRANSPORTE
-- =========================================================
--
-- Tabla y no un texto suelto en cada chofer, por lo mismo
-- que los sectores: escrita a mano, 'MARCOS RULLO' y 'Marcos
-- Rullo' serían dos transportes distintos para la base y el
-- mismo camión en la calle.
--
-- =========================================================

CREATE TABLE IF NOT EXISTS public.empresa_transporte (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    nombre VARCHAR(150) NOT NULL
        CHECK (btrim(nombre) <> ''),

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS empresa_transporte_nombre_unico
    ON public.empresa_transporte (upper(btrim(nombre)));


-- =========================================================
-- 2. LOS CHOFERES
-- =========================================================
--
-- `activo` en vez de borrar: un chofer que deja de trabajar
-- tiene palets y movimientos apuntándole, y borrarlo rompería
-- el historial de quién trajo y quién se llevó cada cosa.
--
-- =========================================================

CREATE TABLE IF NOT EXISTS public.transportista (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    nombre VARCHAR(150) NOT NULL
        CHECK (btrim(nombre) <> ''),

    /* `null` = fletero por su cuenta, sin transporte detrás. */
    empresa_transporte_id BIGINT
        REFERENCES public.empresa_transporte(id)
        ON DELETE SET NULL,

    telefono VARCHAR(30),

    activo BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS transportista_nombre_unico
    ON public.transportista (upper(btrim(nombre)));

CREATE INDEX IF NOT EXISTS transportista_empresa
    ON public.transportista (empresa_transporte_id);


